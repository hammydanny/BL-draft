#!/usr/bin/env node
'use strict';
// Moves every cache-busting reference to the release in js/version.js.
//
//   node scripts/set-version.js            align references with the current APP_VERSION
//   node scripts/set-version.js 0.7.3      set APP_VERSION first, then align
//   node scripts/set-version.js --check    report stale references and unreleased asset edits
//
// Covers HTML asset query strings (`?v=`), the per-character module loader and the
// image/font service-worker cache name. Other query parameters are preserved.
//
// Release fingerprint: scripts/release-manifest.json records a SHA-256 of every file a
// browser can cache under the current version (versioned scripts/stylesheets, every
// character module, images, fonts). `--check` fails when one of those files changed
// while APP_VERSION stayed the same, because returning players would keep the old copy
// (e.g. a character portrait path edited in js/players/<name>/player.js). Moving to a
// new version rewrites the manifest. `--stamp` re-records it for the current version and
// is only correct while that version has not yet been pushed to main.
const crypto=require('node:crypto');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
function walk(dir){return fs.readdirSync(dir,{withFileTypes:true}).flatMap(entry=>entry.name.startsWith('.')||entry.name==='node_modules'?[]:entry.isDirectory()?walk(path.join(dir,entry.name)):[path.join(dir,entry.name)]);}
function currentVersion(){return /const APP_VERSION="([^"]+)"/.exec(read('js/version.js'))[1];}
function expected(version){
    const files={};
    for(const file of walk(root).filter(file=>file.endsWith('.html'))){
        const relative=path.relative(root,file),source=read(relative);
        files[relative]=source.replace(/((?:src|href)="[^"?]+\?v=)[^"&]+/g,(_,prefix)=>prefix+version);
    }
    files['js/players-loader.js']=read('js/players-loader.js').replace(/const version = "[^"]+";/,`const version = "${version}";`);
    files['service-worker.js']=read('service-worker.js').replace(/const CACHE_NAME="bld-static-v[^"]+";/,`const CACHE_NAME="bld-static-v${version}";`);
    return files;
}
function stale(version=currentVersion()){return Object.entries(expected(version)).filter(([file,content])=>read(file)!==content).map(([file])=>file);}
const MANIFEST='scripts/release-manifest.json';
// Every file a returning browser may hold from an earlier visit under this version.
function cachedAssets(){
    const files=new Set();
    for(const file of walk(root).filter(file=>file.endsWith('.html'))){
        const source=read(path.relative(root,file)),dir=path.dirname(file);
        for(const [,url] of source.matchAll(/(?:src|href)="([^"?#]+)\?v=/g)){
            const target=url.startsWith('/BL-draft/')?path.join(root,url.slice(10)):url.startsWith('/')?null:path.resolve(dir,url);
            if(target&&target.startsWith(root)&&fs.existsSync(target))files.add(path.relative(root,target).split(path.sep).join('/'));
        }
    }
    const folders=JSON.parse(/const folders = (\[[^\]]*\]);/.exec(read('js/players-loader.js'))[1]);
    for(const folder of folders)for(const name of ['player.js','reference.js'])files.add(`js/players/${folder}/${name}`);
    for(const dir of ['images','fonts','assets'])if(fs.existsSync(path.join(root,dir)))for(const file of walk(path.join(root,dir)))files.add(path.relative(root,file).split(path.sep).join('/'));
    return [...files].sort();
}
function fingerprint(){const out={};for(const file of cachedAssets())out[file]=fs.existsSync(path.join(root,file))?crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex').slice(0,16):'missing';return out;}
function readManifest(){try{return JSON.parse(read(MANIFEST));}catch{return null;}}
function writeManifest(version=currentVersion()){fs.writeFileSync(path.join(root,MANIFEST),JSON.stringify({version,note:'Generated by node scripts/set-version.js. Do not edit by hand.',files:fingerprint()},null,1)+'\n');}
// Files whose bytes changed (or appeared/disappeared) since the manifest was recorded for this version.
function unreleased(version=currentVersion()){
    const manifest=readManifest();if(!manifest||manifest.version!==version)return ['(manifest missing or recorded for another version)'];
    const now=fingerprint(),names=new Set([...Object.keys(now),...Object.keys(manifest.files||{})]);
    return [...names].filter(file=>now[file]!==manifest.files?.[file]).sort();
}
module.exports={stale,currentVersion,cachedAssets,fingerprint,unreleased,MANIFEST};

if(require.main===module){
    const args=process.argv.slice(2);
    if(args.includes('--check')){
        const files=stale(),changed=unreleased();
        for(const file of files)console.error('STALE',file);
        for(const file of changed)console.error('CHANGED WITHOUT A VERSION BUMP',file);
        console.log(`Version references: ${files.length} stale file(s) for ${currentVersion()}.`);
        console.log(`Release fingerprint: ${changed.length} cached asset(s) changed since ${currentVersion()} was recorded.`);
        if(changed.length)console.log('Run node scripts/set-version.js <next-version>. Use --stamp only if this version has not been pushed to main yet.');
        process.exitCode=files.length||changed.length?1:0;return;
    }
    if(args.includes('--stamp')){const files=stale();if(files.length){console.error('Align version references first: node scripts/set-version.js');process.exitCode=1;return;}writeManifest();console.log(`Release fingerprint recorded for ${currentVersion()}.`);return;}
    const requested=args.find(arg=>/^\d+(?:\.\d+){1,3}$/.test(arg));
    if(requested){const file=path.join(root,'js/version.js');fs.writeFileSync(file,read('js/version.js').replace(/const APP_VERSION="[^"]+";/,`const APP_VERSION="${requested}";`));}
    const version=currentVersion();let written=0;
    const previous=readManifest()?.version;
    for(const [file,content] of Object.entries(expected(version)))if(read(file)!==content){fs.writeFileSync(path.join(root,file),content);written++;}
    // A new version records a fresh fingerprint. Re-running for the same version never
    // hides edits; that needs an explicit --stamp.
    if(previous!==version)writeManifest(version);
    console.log(`Version ${version}: ${written} file(s) updated.`);
}
